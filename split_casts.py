#!/usr/bin/env python3
"""Split an existing Gakumas iCalendar into individual voice-actor feeds.

Input: calendar.ics generated by the Firefox console exporter, where each
VEVENT's DESCRIPTION contains e.g. '出演者: 花岩香奈、小鹿なお'.

Does not access Firestore, run a browser, or need any third-party packages.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from datetime import date, datetime, timedelta, timezone
from hashlib import sha256
from html import escape as html_escape
import json
from pathlib import Path
import re
import shutil
import sys
import tempfile
from urllib.parse import quote

JST = timezone(timedelta(hours=9))
BASE_URL = "https://ivanchan1129.github.io/gakumas-calendar-ics"
SOURCE_SITE = "https://gakusei-cheer-portal.web.app/calendar"
ACTOR_RE = re.compile(r"(?m)^\s*出演者\s*[:：]\s*(.*?)\s*$")
UNKNOWN = {"", "なし", "未定", "不明", "未発表", "不詳", "なし（未定）", "-", "ー"}


def unfold_lines(text: str) -> list[str]:
    """RFC 5545 line unfolding, preserving logical property lines."""
    raw = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    lines: list[str] = []
    for line in raw:
        if (line.startswith(" ") or line.startswith("\t")) and lines:
            lines[-1] += line[1:]
        elif line:
            lines.append(line)
    return lines


def ics_unescape(text: str) -> str:
    # Escape sequences in TEXT values: \\, \\n, \\, and \\;.
    return re.sub(r"\\([nN\\,;])", lambda m: "\n" if m[1] in ("n", "N") else m[1], text)


def ics_escape(text: str) -> str:
    return (text.replace("\\", "\\\\").replace("\r\n", "\n")
            .replace("\r", "\n").replace("\n", "\\n")
            .replace(",", "\\,").replace(";", "\\;"))


def fold(line: str) -> list[str]:
    parts = []
    cur = ""
    byte_count = 0
    for ch in line:
        n = len(ch.encode("utf-8"))
        if byte_count + n > 75:
            parts.append(cur)
            cur = " " + ch
            byte_count = 1 + n
        else:
            cur += ch
            byte_count += n
    parts.append(cur)
    return parts


def get_prop(component: list[str], name: str) -> str | None:
    for line in component:
        key, colon, value = line.partition(":")
        if colon and key.split(";", 1)[0].upper() == name.upper():
            return value
    return None


def extract_casts(component: list[str]) -> list[str]:
    desc = get_prop(component, "DESCRIPTION")
    if desc is None:
        return []
    decoded = ics_unescape(desc)
    result: list[str] = []
    for m in ACTOR_RE.finditer(decoded):
        for raw in re.split(r"\s*(?:、|，|,|／|/|;|；|\s+&\s+)\s*", m[1]):
            cast = raw.strip().strip("・• \t")
            if cast and cast not in UNKNOWN and cast not in result:
                result.append(cast)
    return result


def parse_date_prop(component: list[str], name: str) -> date | None:
    """Interpret DTSTART/DTEND dates in Japan; DATE values remain calendar days."""
    for line in component:
        key, sep, value = line.partition(":")
        if not sep or key.split(";", 1)[0].upper() != name:
            continue
        value = value.strip()
        if re.fullmatch(r"\d{8}", value):
            return datetime.strptime(value, "%Y%m%d").date()
        fmt = "%Y%m%dT%H%M%S" if re.fullmatch(r"\d{8}T\d{6}Z?", value) else "%Y%m%dT%H%M"
        try:
            dt = datetime.strptime(value.rstrip("Z"), fmt)
            if value.endswith("Z"):
                dt = dt.replace(tzinfo=timezone.utc).astimezone(JST)
            # If TZID is something other than Asia/Tokyo, leave the calendar
            # date as authored; source exporter writes UTC or DATE values.
            return dt.date()
        except ValueError:
            return None
    return None


def is_current_or_future(component: list[str], today: date) -> bool:
    start = parse_date_prop(component, "DTSTART")
    if not start:
        return False
    if start >= today:
        return True
    end = parse_date_prop(component, "DTEND")
    if not end:
        return False
    # DATE DTEND is exclusive; UTC timestamps are actual ending instants.
    key = next((x.partition(":")[0].upper() for x in component if x.upper().startswith("DTSTART")), "")
    if "VALUE=DATE" in key or re.fullmatch(r"\d{8}", get_prop(component, "DTSTART") or ""):
        return end > today
    return end >= today


def read_calendar(path: Path) -> tuple[list[str], list[list[str]], list[str]]:
    """Read VEVENTs while retaining non-VEVENT calendar parts and properties."""
    text = path.read_text(encoding="utf-8-sig")
    lines = unfold_lines(text)
    if not lines or lines[0].upper() != "BEGIN:VCALENDAR" or lines[-1].upper() != "END:VCALENDAR":
        raise ValueError("输入不是有效的 VCALENDAR（应以 BEGIN:VCALENDAR 开头、END:VCALENDAR 结尾）")
    outer: list[str] = []
    events: list[list[str]] = []
    event = None
    for line in lines[1:-1]:
        if line.upper() == "BEGIN:VEVENT":
            if event is not None:
                raise ValueError("VEVENT 嵌套错误")
            event = [line]
        elif line.upper() == "END:VEVENT":
            if event is None:
                raise ValueError("存在无对应 BEGIN:VEVENT 的 END:VEVENT")
            event.append(line)
            events.append(event)
            event = None
        elif event is not None:
            event.append(line)
        else:
            if not line.upper().startswith("X-WR-CALNAME:"):
                outer.append(line)
    if event is not None:
        raise ValueError("VEVENT 未正常结束")
    return outer, events, lines


def make_calendar(outer: list[str], events: list[list[str]], cast: str) -> bytes:
    lines = ["BEGIN:VCALENDAR"]
    if not any(x.upper().startswith("VERSION:") for x in outer):
        lines.append("VERSION:2.0")
    lines.extend(outer)
    lines.append("X-WR-CALNAME:" + ics_escape(f"学マス声優｜{cast}"))
    for event in events:
        lines.extend(event)
    lines.append("END:VCALENDAR")
    return ("\r\n".join(part for line in lines for part in fold(line)) + "\r\n").encode("utf-8")


def split(source: Path, outdir: Path, *, base_url: str, today: date | None = None) -> list[dict]:
    today = today or datetime.now(JST).date()
    if not source.exists():
        raise FileNotFoundError(f"找不到 {source}，先上传总日历 calendar.ics 到仓库根目录")
    outer, events, _ = read_calendar(source)
    by_cast: dict[str, list[list[str]]] = defaultdict(list)
    no_cast = 0
    expired = 0
    for event in events:
        if not is_current_or_future(event, today):
            expired += 1
            continue
        casts = extract_casts(event)
        if not casts:
            no_cast += 1
            continue
        for cast in casts:
            by_cast[cast].append(event)

    # Keep the existing subscription URL for an actor even if they currently
    # have no upcoming events. A zero-event VCALENDAR is valid and preferable
    # to turning a user's existing Google Calendar subscription into a 404.
    previous_casts: set[str] = set()
    previous_index = outdir / "index.json"
    if previous_index.is_file():
        try:
            previous = json.loads(previous_index.read_text(encoding="utf-8"))
            previous_casts = {item["name"] for item in previous.get("casts", [])
                              if isinstance(item.get("name"), str) and item["name"]}
        except (ValueError, KeyError, TypeError):
            raise ValueError("旧的 casts/index.json 无法读取；为防止误删订阅日历，已中止")
    # If the source contains no cast labels at all, the input may have changed
    # format; refuse to silently publish empty casts. If we have previously
    # valid casts, we can still publish their empty feeds after events expire.
    if not by_cast and not previous_casts:
        raise ValueError(
            "没有找到带有『出演者: 姓名』的今天及未来活动，未覆盖旧日历。"
            "请检查 calendar.ics 的 DESCRIPTION 是否包含出演者字段。"
        )
    for cast in previous_casts:
        by_cast.setdefault(cast, [])
    if outdir.resolve() == source.parent.resolve():
        raise ValueError("输出必须是独立的 casts/ 子目录，避免删除总日历")
    base = base_url.rstrip("/")
    manifest = []
    temp = Path(tempfile.mkdtemp(prefix=".casts_build_", dir=outdir.parent))
    try:
        for cast in sorted(by_cast):
            filename = "cast-" + sha256(cast.encode("utf-8")).hexdigest()[:16] + ".ics"
            data = make_calendar(outer, by_cast[cast], cast)
            (temp / filename).write_bytes(data)
            manifest.append({"name": cast, "count": len(by_cast[cast]), "file": filename,
                             "url": f"{base}/casts/{filename}"})
        (temp / "index.json").write_text(json.dumps({
            "source": "calendar.ics", "generated_for_date_jst": today.isoformat(),
            "source_event_count": len(events), "excluded_expired": expired,
            "excluded_without_cast": no_cast, "casts": manifest
        }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        rows = "\n".join(
            f'<tr><td>{html_escape(x["name"])}</td><td>{x["count"]}</td>'
            f'<td><a href="{quote(x["file"])}">订阅 ICS</a></td></tr>' for x in manifest
        )
        html = ("<!doctype html><html lang=\"zh-CN\"><head><meta charset=\"utf-8\">"
                "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
                "<title>学マス声优独立日历</title>"
                "<style>body{font:16px system-ui,sans-serif;max-width:850px;margin:3em auto;padding:0 1em;}"
                "table{border-collapse:collapse;width:100%;}td,th{padding:.65em;border-bottom:1px solid #ddd;text-align:left;}"
                "a{color:#1265bb;}small{color:#555;}</style></head><body>"
                "<h1>学マス声优独立 ICS 日历</h1><p>按原始日历中的「出演者」拆分，"
                "每位声优可单独订阅；多人出演的节目会出现在各自的日历中。</p>"
                f"<p><small>数据日期（日本时间）：{today.isoformat()}。源日历更新后才会包含新节目。</small></p>"
                "<table><thead><tr><th>声优</th><th>事项数</th><th>链接</th></tr></thead><tbody>"
                + rows + "</tbody></table></body></html>\n")
        (temp / "index.html").write_text(html, encoding="utf-8")
        # Replace entire managed directory only after a valid build.
        backup = outdir.with_name(outdir.name + ".previous")
        if backup.exists():
            shutil.rmtree(backup)
        if outdir.exists():
            outdir.rename(backup)
        try:
            temp.rename(outdir)
        except Exception:
            if backup.exists() and not outdir.exists():
                backup.rename(outdir)
            raise
        if backup.exists():
            shutil.rmtree(backup)
    finally:
        if temp.exists():
            shutil.rmtree(temp)
    print(f"读取总日历 {len(events)} 项；排除过期 {expired} 项；无出演者 {no_cast} 项。")
    print(f"生成 {len(manifest)} 位声优的独立 ICS，合计 {sum(x['count'] for x in manifest)} 条声优-活动关联。")
    print(f"索引：{outdir / 'index.html'}")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description="从学マス calendar.ics 自动拆分每位出演声优的独立 ICS")
    parser.add_argument("--input", type=Path, default=Path("calendar.ics"))
    parser.add_argument("--output-dir", type=Path, default=Path("casts"))
    parser.add_argument("--base-url", default=BASE_URL)
    args = parser.parse_args()
    try:
        args.output_dir.parent.mkdir(parents=True, exist_ok=True)
        split(args.input, args.output_dir, base_url=args.base_url)
    except Exception as exc:
        print(f"拆分失败：{exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
